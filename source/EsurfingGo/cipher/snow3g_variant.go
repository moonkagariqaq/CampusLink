type Snow3GVariant struct {
	key []byte
	iv  []byte
}

func NewSnow3GVariant(key, iv []byte) *Snow3GVariant {
	k := make([]byte, snow3gKeySize)
	copy(k, key)
	v := make([]byte, snow3gIVSize)
	copy(v, iv)
	return &Snow3GVariant{key: k, iv: v}
}

func NewSnow3gVariant(key, iv []byte) Cipher {
	return NewSnow3GVariant(key, iv)
}

func snow3gSBox(x uint32) uint32 {
	return (uint32(snow3gS0[x>>24]) << 24) |
		(uint32(snow3gS1[(x>>16)&0xFF]) << 16) |
		(uint32(snow3gS0[(x>>8)&0xFF]) << 8) |
		uint32(snow3gS1[x&0xFF])
}

func snow3gFSM(c []uint32) uint32 {
	v1 := c[1]
	v2 := c[3] + c[0]
	v3 := c[4] ^ v1
	v4 := (c[0] ^ c[2]) + v1
	v5 := (v2 << 16) | (v3 >> 16)
	v6 := v2 >> 14
	v7 := v2 >> 6
	v8 := v2 >> 16
	v9 := (v3 << 16) | (v2 >> 16)

	t1 := uint32((((uint64(v3>>16) << 32) | uint64(v5)) >> 14) & 0xFFFFFFFF)
	t2 := uint32((((uint64(v3>>16) << 32) | uint64(v5)) >> 8) & 0xFFFFFFFF)
	v10 := ((v6 & 3) | (4 * v5)) ^ v5 ^ ((v7 & 0x3FF) | (v5 << 10)) ^ t1 ^ t2

	t3 := uint32((((uint64(v8) << 32) | uint64(v9)) >> 10) & 0xFFFFFFFF)
	t4 := uint32((((uint64(v8) << 32) | uint64(v9)) >> 2) & 0xFFFFFFFF)
	v11 := (((v3 >> 8) & 0xFF) | (v9 << 8)) ^ v9 ^ (((v3 & 0xFFFF) >> 2) | (v9 << 14)) ^ t3 ^ t4

	c[0] = snow3gSBox(v10)
	c[1] = snow3gSBox(v11)
	return v4
}

func snow3GKeySchedule(c []uint32, key, iv []byte) {
	for i := range c {
		c[i] = 0
	}
	for i := 0; i < 16; i++ {
		c[i+6] = (uint32(iv[i]) & 0x807FFFFF) | (uint32(key[i]) << 23) | ((snow3gD[i] & 0x7FFFFF) << 8)
	}

	v9 := c[21]
	v10 := c[20] & 0xFFFF
	v11 := c[17]
	v12 := c[15]
	v13 := c[13]
	v14 := c[11]
	v15 := c[8]
	v16 := c[6]

	rounds := 32
	for rounds > 0 {
		rounds--
		c[2] = uint32(uint16(v10)) | (uint32(uint16(v9>>15)) << 16)
		c[3] = (v12 >> 15) | (v11 << 16)
		c[4] = (v14 >> 15) | (v13 << 16)
		c[5] = (v16 >> 15) | (v15 << 16)

		v18 := snow3gFSM(c)
		v19Hi := (uint64(c[13]) << 32) | uint64(c[12])
		v20 := (uint64(c[20]) << 32) | uint64(c[19])
		v15n := c[9]
		v16n := c[7]
		c[7] = c[8]
		v22Lo := (uint64(c[15]) << 32) | uint64(c[14])
		v22Hi := (uint64(c[17]) << 32) | uint64(c[16])
		v23 := (((c[6] & 0x7FFFFF) << 8) | (c[6] >> 23)) + c[6]
		v24 := (((c[10] & 0x7FF) << 20) | (c[10] >> 11)) + (v23 >> 31) + (v23 & 0x7FFFFFFF)
		v25 := (((c[16] & 0x3FF) << 21) | (c[16] >> 10)) + (v24 >> 31) + (v24 & 0x7FFFFFFF)
		v10n := c[21]
		v12n := uint32(v22Hi & 0xFFFFFFFF)
		v26 := (((c[19] & 0x3FFF) << 17) | (c[19] >> 14)) + (v25 >> 31) + (v25 & 0x7FFFFFFF)
		v27 := (((v10n & 0xFFFF) << 15) | (v10n >> 16)) + (v26 >> 31) + (v26 & 0x7FFFFFFF)
		v11n := c[18]
		v28 := (v27 >> 31) + (v18 >> 1) + (v27 & 0x7FFFFFFF)
		v14n := uint32(v19Hi & 0xFFFFFFFF)
		v13n := uint32(v22Lo & 0xFFFFFFFF)
		v9n := (v28 & 0x7FFFFFFF) + (v28 >> 31)

		c[9] = c[10]
		c[10] = c[11]
		c[11] = c[12]
		c[12] = uint32(v19Hi >> 32)
		c[18] = c[19]
		c[19] = uint32(v20 >> 32)
		c[6] = v16n
		c[8] = v15n
		c[13] = uint32(v22Lo & 0xFFFFFFFF)
		c[14] = uint32(v22Lo >> 32)
		c[15] = uint32(v22Hi & 0xFFFFFFFF)
		c[16] = uint32(v22Hi >> 32)
		c[17] = v11n
		c[20] = v10n
		c[21] = v9n

		v9 = v9n
		v10 = v10n
		v11 = v11n
		v12 = v12n
		v13 = v13n
		v14 = v14n
		v15 = v15n
		v16 = v16n
	}
}

func snow3GGenerate(c []uint32, in []byte, blocks int, out []byte) {
	v4 := (c[15] >> 15) | (c[17] << 16)
	v5 := (c[11] >> 15) | (c[13] << 16)
	v6 := (c[6] >> 15) | (c[8] << 16)
	c[2] = uint32(uint16(c[20])) | (uint32(uint16(c[21]>>15)) << 16)
	c[3] = v4
	c[4] = v5
	c[5] = v6
	snow3gFSM(c)

	for i := 0; ; i++ {
		rLo := (uint64(c[11]) << 32) | uint64(c[10])
		rHi := (uint64(c[13]) << 32) | uint64(c[12])
		v13 := c[7]
		v14 := c[18]
		v15 := c[19]
		v17 := c[20]
		v16 := c[21]
		v18 := c[6]
		c[7] = c[8]
		c[18] = v15
		c[19] = v17
		v19Lo := (uint64(c[15]) << 32) | uint64(c[14])
		v19Hi := (uint64(c[17]) << 32) | uint64(c[16])
		v20 := (((v18 & 0x7FFFFF) << 8) | (v18 >> 23)) + v18
		v21 := (((uint32(rLo) & 0x7FF) << 20) | (uint32(rLo) >> 11)) + (v20 >> 31) + (v20 & 0x7FFFFFFF)
		v22 := (((c[16] & 0x3FF) << 21) | (c[16] >> 10)) + (v21 >> 31) + (v21 & 0x7FFFFFFF)
		v23 := (((v15 & 0x3FFF) << 17) | (v15 >> 14)) + (v22 >> 31) + (v22 & 0x7FFFFFFF)
		v24 := c[9]
		v25 := (((v16 & 0xFFFF) << 15) | (v16 >> 16)) + (v23 >> 31) + (v23 & 0x7FFFFFFF)
		v26 := (v25 & 0x7FFFFFFF) + (v25 >> 31)
		oldC16 := c[16]

		c[6] = v13
		c[8] = v24
		c[9] = c[10]
		c[10] = c[11]
		c[11] = c[12]
		c[12] = uint32(rHi >> 32)
		c[13] = uint32(v19Lo & 0xFFFFFFFF)
		c[14] = uint32(v19Lo >> 32)
		c[15] = uint32(v19Hi & 0xFFFFFFFF)
		c[16] = uint32(v19Hi >> 32)
		c[17] = v14
		c[20] = v16
		c[21] = v26

		if i >= blocks {
			break
		}

		c[2] = uint32(uint16(v16)) | (uint32(uint16(v26>>15)) << 16)
		c[3] = (v14 << 16) | (oldC16 >> 15)
		c[4] = (uint32(v19Lo) << 16) | (uint32(rHi&0xFFFFFFFF) >> 15)
		c[5] = (v24 << 16) | (v13 >> 15)
		ks := snow3gFSM(c) ^ c[5]

		// On little-endian hosts, in is loaded as uint32le, then bswap32 (to BE),
		// XORed with ks, then bswap32 and written back to out.
		// That corresponds directly to binary.BigEndian uint32 operations.
		pt := binary.BigEndian.Uint32(in[i*4:])
		binary.BigEndian.PutUint32(out[i*4:], pt^ks)
	}
}

func (s *Snow3GVariant) Encrypt(text string) string {
	data := []byte(text)
	pad := 0
	if rem := len(data) & 3; rem != 0 {
		pad = 4 - rem
	}
	total := len(data) + pad
	buf := make([]byte, total)
	copy(buf, data)

	c := make([]uint32, snow3gCells)
	snow3GKeySchedule(c, s.key, s.iv)
	snow3GGenerate(c, buf, total/4, buf)

	return strings.ToUpper(hex.EncodeToString(buf))
}

func (s *Snow3GVariant) Decrypt(hexStr string) string {
	data, err := hex.DecodeString(hexStr)
	if err != nil || len(data) == 0 {
		return ""
	}

	buf := make([]byte, len(data))
	copy(buf, data)

	c := make([]uint32, snow3gCells)
	snow3GKeySchedule(c, s.key, s.iv)
	snow3GGenerate(c, buf, len(data)/4, buf)

	// Strip trailing zeros
	outLen := len(buf)
	for outLen > 0 && buf[outLen-1] == 0 {
		outLen--
	}
	return string(buf[:outLen])
}

